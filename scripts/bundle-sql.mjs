#!/usr/bin/env node
/**
 * Concatenate the migrations and the seeds into two pasteable files.
 *
 * Setting a project up by hand means opening seventeen files in order and not
 * losing your place. Order is the part that matters — a migration that runs
 * before the one it depends on fails in a way that looks like a bug in the
 * schema — so this does the ordering and leaves the person only the pasting.
 *
 * Equivalent to `supabase db push` followed by the seeds, for anyone who has
 * not linked the CLI. Writes to supabase/bundle/, which is git-ignored.
 *
 *   node scripts/bundle-sql.mjs
 */

import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = process.cwd();
const outputDir = resolve(root, 'supabase/bundle');

const bold = (text) => `[1m${text}[0m`;
const green = (text) => `[32m${text}[0m`;

function bundle(sourceDir, outputName, heading) {
  const directory = resolve(root, sourceDir);
  const files = readdirSync(directory)
    .filter((name) => name.endsWith('.sql'))
    // Filenames are zero-padded, so a plain sort is the intended order. Sorted
    // explicitly rather than trusting readdir, which is not ordered on all
    // filesystems and would fail silently and confusingly if it were wrong.
    .sort((a, b) => a.localeCompare(b, 'en'));

  const parts = files.map((name) => {
    const body = readFileSync(resolve(directory, name), 'utf8');
    return `-- ${'='.repeat(74)}\n-- ${sourceDir}/${name}\n-- ${'='.repeat(74)}\n\n${body}`;
  });

  const header =
    `-- ${heading}\n` +
    `-- Generated by scripts/bundle-sql.mjs — do not edit.\n` +
    `-- ${files.length} files, in the order they must run.\n\n`;

  writeFileSync(resolve(outputDir, outputName), header + parts.join('\n\n'), 'utf8');
  return files;
}

mkdirSync(outputDir, { recursive: true });

const migrations = bundle('supabase/migrations', 'all-migrations.sql', 'Schema — run this FIRST');
const seeds = bundle('supabase/seed', 'all-seeds.sql', 'Reference data — run this SECOND');

console.log(bold('\nWrote two files to supabase/bundle/\n'));
console.log(`${green('1.')} all-migrations.sql  — ${migrations.length} migrations, creates every table and policy`);
console.log(`${green('2.')} all-seeds.sql       — ${seeds.length} seeds, fills the exercise and food catalogues`);
console.log(
  '\nPaste them into the Supabase SQL editor in that order, one at a time, and wait for\n' +
    'each to finish. Running the seeds before the migrations fails — the tables are not\n' +
    'there yet.\n',
);
